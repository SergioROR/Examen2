class Producto{
    constructor({
        id_producto,
        nombre,
        descripcion,
        modelo,
        num_serie,
        cantidad,
        creado_el, 
        actualizado_el, 
        id_departamento
    }
    ){
        this.id_departamento = id_producto;
        this.nombre = nombre;
        this.descripcion = descripcion;
        this.modelo = modelo;
        this.num_serie = num_serie;
        this.cantidad = cantidad;
        this.creado_el = creado_el;
        this.actualizado_el = actualizado_el;
        this.id_departamento = id_departamento;
    }
}